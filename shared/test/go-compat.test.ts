/**
 * The gate that proves the worker accepts real wuzapi traffic.
 *
 * Every fixture in fixtures/wuzapi-hmac.json was produced by Go's own standard
 * library (cloudflare/tools/hmac-fixture), reproducing exactly what wuzapi signs
 * for each delivery mode. If these pass, an `x-hmac-signature` header generated
 * by wuzapi verifies in the worker byte-for-byte.
 */
import { describe, expect, it } from "vitest";
import fixturesFile from "./fixtures/wuzapi-hmac.json";
import {
  bytesToHex,
  hmacSha256Hex,
  hmacSha256HexStream,
  matchesAnyKey,
  timingSafeEqualString,
} from "../src/lib/hmac";

interface Fixture {
  name: string;
  note: string;
  contentType: string;
  key: string;
  body: string;
  signature: string;
}

const fixtures = (fixturesFile as { fixtures: Fixture[] }).fixtures;

function streamOf(text: string): ReadableStream<Uint8Array> {
  const bytes = new TextEncoder().encode(text);
  return new ReadableStream<Uint8Array>({
    start(controller) {
      // Two chunks on purpose: the streaming HMAC must not care about framing.
      const half = Math.floor(bytes.byteLength / 2);
      controller.enqueue(bytes.subarray(0, half));
      controller.enqueue(bytes.subarray(half));
      controller.close();
    },
  });
}

describe("wuzapi HMAC compatibility (fixtures generated by Go)", () => {
  it("has fixtures for every delivery mode", () => {
    expect(fixtures.map((fixture) => fixture.name).sort()).toEqual([
      "form-event-message",
      "form-special-characters",
      "json-event-message",
      "json-event-unicode",
      "json-global-webhook",
      "media-form-with-file",
      "media-json-inline-base64",
    ]);
  });

  for (const fixture of fixtures) {
    it(`verifies ${fixture.name}`, async () => {
      const key = new TextEncoder().encode(fixture.key);
      const body = new TextEncoder().encode(fixture.body);

      // One-shot (buffered) verification, as used for small payloads.
      expect(await hmacSha256Hex(key, body)).toBe(fixture.signature);

      // Streaming verification, as used for oversized media payloads.
      expect(await hmacSha256HexStream(key, streamOf(fixture.body))).toBe(fixture.signature);

      // And through the keyring matcher the ingest handler uses.
      expect(await matchesAnyKey([fixture.key], fixture.signature, body)).toBe(true);
    });

    it(`rejects a tampered ${fixture.name}`, async () => {
      const tampered = new TextEncoder().encode(`${fixture.body} `);
      expect(await matchesAnyKey([fixture.key], fixture.signature, tampered)).toBe(false);
      expect(await matchesAnyKey(["another-key"], fixture.signature, new TextEncoder().encode(fixture.body))).toBe(
        false,
      );
      expect(await matchesAnyKey([fixture.key], null, new TextEncoder().encode(fixture.body))).toBe(false);
    });
  }

  it("propagates Go's HTML escaping, which is what wuzapi actually sends", () => {
    const message = fixtures.find((fixture) => fixture.name === "json-event-message");
    expect(message).toBeDefined();
    // Go escapes <, > and & inside JSON strings; the worker must never re-encode
    // the body before hashing it.
    expect(message?.body).toContain("\\u0026");
    expect(message?.body).toContain("\\u003c");
  });

  it("accepts any key in the rotation keyring", async () => {
    const fixture = fixtures[0] as Fixture;
    const body = new TextEncoder().encode(fixture.body);
    expect(await matchesAnyKey(["old-key", fixture.key, "new-key"], fixture.signature, body)).toBe(true);
  });
});

describe("constant-time comparison", () => {
  it("matches equal strings and rejects different ones", async () => {
    expect(await timingSafeEqualString("token-abcdef", "token-abcdef")).toBe(true);
    expect(await timingSafeEqualString("token-abcdef", "token-abcdeg")).toBe(false);
    expect(await timingSafeEqualString("short", "much-longer-token")).toBe(false);
    expect(await timingSafeEqualString("", "")).toBe(true);
  });
});

describe("streaming HMAC equals one-shot HMAC", () => {
  it("agrees for a 2 MB body split across many chunks", async () => {
    const key = new TextEncoder().encode("wuzapi-test-hmac-key-0123456789abcdef");
    const body = new Uint8Array(2 * 1024 * 1024);
    crypto.getRandomValues(body.subarray(0, 65_536));
    // Fill the rest deterministically to keep the test fast but non-trivial.
    for (let i = 65_536; i < body.byteLength; i++) body[i] = (i * 31) & 0xff;

    const stream = new ReadableStream<Uint8Array>({
      start(controller) {
        for (let offset = 0; offset < body.byteLength; offset += 65_536) {
          controller.enqueue(body.subarray(offset, Math.min(offset + 65_536, body.byteLength)));
        }
        controller.close();
      },
    });

    const [oneShot, streamed] = await Promise.all([hmacSha256Hex(key, body), hmacSha256HexStream(key, stream)]);
    expect(streamed).toBe(oneShot);
  });

  it("handles keys longer and shorter than the HMAC block size", async () => {
    for (const keyText of ["k", "0123456789abcdef", "x".repeat(200)]) {
      const key = new TextEncoder().encode(keyText);
      const body = new TextEncoder().encode("payload");
      const oneShot = await hmacSha256Hex(key, body);
      const streamed = await hmacSha256HexStream(key, streamOf("payload"));
      expect(streamed).toBe(oneShot);
    }
  });

  it("hashes empty bodies consistently", async () => {
    const key = new TextEncoder().encode("key");
    expect(await hmacSha256HexStream(key, streamOf(""))).toBe(await hmacSha256Hex(key, new Uint8Array()));
  });
});

describe("hex helpers", () => {
  it("round-trips bytes", () => {
    expect(bytesToHex(new Uint8Array([0x00, 0x0f, 0xff]))).toBe("000fff");
  });
});
