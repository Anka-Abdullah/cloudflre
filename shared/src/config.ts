export class ConfigError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "ConfigError";
  }
}

function intVar(name: string, raw: string | undefined, fallback: number, min: number, max: number): number {
  if (raw === undefined || raw.trim() === "") return fallback;
  const parsed = Number(raw);
  if (!Number.isFinite(parsed) || !Number.isInteger(parsed)) {
    throw new ConfigError(`${name} must be an integer, received ${JSON.stringify(raw)}`);
  }
  if (parsed < min || parsed > max) {
    throw new ConfigError(`${name} must be between ${min} and ${max}, received ${parsed}`);
  }
  return parsed;
}

function enumVar<T extends string>(name: string, raw: string | undefined, allowed: readonly T[], fallback: T): T {
  if (raw === undefined || raw.trim() === "") return fallback;
  const value = raw.trim().toLowerCase() as T;
  if (!allowed.includes(value)) {
    throw new ConfigError(`${name} must be one of ${allowed.join(", ")}, received ${JSON.stringify(raw)}`);
  }
  return value;
}

function boolVar(name: string, raw: string | undefined, fallback: boolean): boolean {
  if (raw === undefined || raw.trim() === "") return fallback;
  const value = raw.trim().toLowerCase();
  if (value === "true" || value === "1" || value === "yes") return true;
  if (value === "false" || value === "0" || value === "no") return false;
  throw new ConfigError(`${name} must be true or false, received ${JSON.stringify(raw)}`);
}

function trimmed(raw: string | undefined): string {
  return (raw ?? "").trim();
}

/** Base URL without a trailing slash, so paths can be appended directly. */
function baseUrl(raw: string | undefined): string {
  return trimmed(raw).replace(/\/+$/, "");
}

