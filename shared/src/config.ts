export function loadConfig(env: Env): InstanceConfig {
  const slug = trimmed(env.INSTANCE_SLUG);
  if (!/^[1-9][0-9]{7,14}$/.test(slug)) {
    throw new ConfigError(
      `INSTANCE_SLUG must be an E.164 number without '+', received ${JSON.stringify(env.INSTANCE_SLUG)}`,
    );
  }

  return {
    slug,
    hmacMode: enumVar("HMAC_MODE", env.HMAC_MODE, ["strict", "optional", "off"] as const, "strict"),
    mediaMode: enumVar("MEDIA_MODE", env.MEDIA_MODE, ["r2", "reject"] as const, "r2"),
    relayMode: enumVar("RELAY_MODE", env.RELAY_MODE, ["relay", "observe"] as const, "relay"),
    inlineMaxBytes: intVar("INLINE_MAX_BYTES", env.INLINE_MAX_BYTES, 90_000, 1_000, 127_000),
    mediaBufferMaxBytes: intVar(
      "MEDIA_BUFFER_MAX_BYTES",
      env.MEDIA_BUFFER_MAX_BYTES,
      25_000_000,
      1_000,
      100_000_000,
    ),
    scanMaxFieldBytes: intVar("SCAN_MAX_FIELD_BYTES", env.SCAN_MAX_FIELD_BYTES, 262_144, 1_024, 5_000_000),
    retryBaseSeconds: intVar("RETRY_BASE_SECONDS", env.RETRY_BASE_SECONDS, 15, 1, 3_600),
    retryMaxSeconds: intVar("RETRY_MAX_SECONDS", env.RETRY_MAX_SECONDS, 3_600, 1, 86_400),
    downstreamUrl: trimmed(env.DOWNSTREAM_URL),
    r2PublicBaseUrl: trimmed(env.R2_PUBLIC_BASE_URL).replace(/\/+$/, ""),
    dlqQueueName: trimmed(env.DLQ_QUEUE_NAME),
    ingestToken: trimmed(env.INGEST_TOKEN),
    hmacKeys: trimmed(env.WUZAPI_HMAC_KEYS)
      .split(",")
      .map((key) => key.trim())
      .filter((key) => key.length > 0),
    downstreamHmacKey: trimmed(env.DOWNSTREAM_HMAC_KEY),
    alertWebhookUrl: trimmed(env.ALERT_WEBHOOK_URL),
    bot: loadBotConfig(env),
  };
}

export interface BotReadiness {
  /** True when the chat pipeline can answer a customer without losing a message. */
  ready: boolean;
  /** Configuration names that are still empty; never contains a secret value. */
  missing: string[];
  /** Bindings the pipeline needs but the deployment does not declare. */
  missingBindings: string[];
}

/**
 * Reports what the bot pipeline is still missing. Used by `/healthz` and by the
 * queue consumer, so a half-provisioned number logs one clear reason instead of
 * throwing per event.
 *
 * `BOT_MODE=off` never consults this: relay behaviour must survive a number that
 * has no D1/KV/DO bindings at all.
 */
export function botReadiness(config: InstanceConfig, env: Pick<Env, "BOT_DB" | "CHAT_COORDINATOR">): BotReadiness {
  const missing: string[] = [];
  const { bot } = config;
  if (bot.wuzapiApiBase === "") missing.push("WUZAPI_API_BASE");
  if (bot.wuzapiToken === "") missing.push("WUZAPI_TOKEN");
  if (bot.aiBaseUrl === "") missing.push("AI_BASE_URL");
  if (bot.aiModel === "") missing.push("AI_MODEL");
  if (bot.aiApiKey === "") missing.push("AI_API_KEY");

  const missingBindings: string[] = [];
  if (!env.BOT_DB) missingBindings.push("BOT_DB");
  if (!env.CHAT_COORDINATOR) missingBindings.push("CHAT_COORDINATOR");

  return { ready: missing.length === 0 && missingBindings.length === 0, missing, missingBindings };
}
