/**
 * Per-number configuration.
 *
 * Every value comes from the instance's `wrangler.jsonc` (`vars`) or from
 * `wrangler secret put`, so one number's worker never reads another number's
 * settings and the shared code stays free of hard-coded names.
 *
 * The file has two halves:
 *
 *  1. the relay settings (HMAC, R2 offload, DLQ) that already existed, and
 *  2. `bot`, the automation settings of section 9 of the work plan, kept nested
 *     so `BOT_MODE=off` can run with only the original bindings present.
 */
import type { DlqRecord, EnvelopeV1 } from "./envelope";

